String tr(String ar) {
  if (session.lang != 'ckb') return ar;
  final exact = _ckb[ar];
  if (exact != null) return exact;
  var out = ar;
  for (final part in _ckbParts) {
    out = out.replaceAll(part[0], part[1]);
  }
  return out;
}

